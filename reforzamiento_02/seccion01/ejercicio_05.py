Entero_positivo = 4
print("Número inicial:", Entero_positivo)
potencia = (Entero_positivo ** 6)
print("Potencia elevada a 6:", potencia)
multiplicacion = Entero_positivo * 2
print("Número multiplicado por 2:", multiplicacion)
resta = potencia - multiplicacion
print("Resultado de la resta:", resta)
residuo = resta % 5
print("Residuo de dividir entre 5:", residuo)

